const I18N = {
  lang: localStorage.getItem('tsmhst.lang') || 'en',
  dicts: Object.assign({}, PARTIAL),
  coverage(code) {
    if (code === 'en') return 'full';
    if (code === 'sw') return 'partial';
    return PARTIAL[code] ? 'partial' : 'fallback';
  },
  t(text, vars) {
    const dict = this.dicts[this.lang] || {};
    let out = dict[text] || text;
    if (vars) Object.keys(vars).forEach(k => { out = out.split('{' + k + '}').join(vars[k]); });
    return out;
  },
  setLang(code) {
    if (!LANGUAGES.some(l => l.code === code)) code = 'en';
    this.lang = code;
    localStorage.setItem('tsmhst.lang', code);
    document.documentElement.lang = code;
    document.documentElement.dir = ['ar', 'he', 'fa', 'ur'].includes(code) ? 'rtl' : 'ltr';
  },
  languageName(code) {
    const l = LANGUAGES.find(x => x.code === code);
    return l ? l.name : 'English';
  }
};
I18N.setLang(I18N.lang);
